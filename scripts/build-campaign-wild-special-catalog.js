#!/usr/bin/env node
/* Development-only: build checked-in offline data for optional special encounters. */
const fs = require('node:fs');
const path = require('node:path');
const Draft = require('../assets/js/campaign/campaign-battle-fallback-catalog.js');

const LEGENDARY_IDS = Object.freeze([
  249, 250, 382, 384, 485, 488, 641, 716, 718, 785, 786, 787, 788,
  888, 891, 892, 1001, 1002, 1003
]);
const MYTHICAL_IDS = Object.freeze([251, 490, 647, 491, 721, 802]);
const ids = [...LEGENDARY_IDS, ...MYTHICAL_IDS];
const outputPath = path.join(__dirname, '..', 'assets', 'js', 'campaign', 'campaign-wild-special-catalog.js');
const knownMoves = new Map(Object.values(Draft.byId)
  .flatMap(species => species.moves.map(move => [move.name, move])));

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error('PokéAPI ' + response.status + ': ' + url);
  return response.json();
}

function chooseMoves(pokemon, types) {
  const available = [...new Map(pokemon.moves
    .map(item => knownMoves.get(item.move.name))
    .filter(Boolean)
    .map(move => [move.name, move])).values()]
    .filter(move => move.power > 0);
  const score = move => move.power + (types.includes(move.type) ? 100 : 0)
    + (move.accuracy === null ? 10 : move.accuracy / 10);
  available.sort((a, b) => score(b) - score(a) || a.name.localeCompare(b.name));
  const chosen = [];
  for (const move of available) {
    if (chosen.length === 4) break;
    if (chosen.some(other => other.name === move.name)) continue;
    if (chosen.length < 2 && chosen.some(other => other.type === move.type)
      && available.some(other => !chosen.includes(other) && other.type !== move.type)) continue;
    chosen.push(move);
  }
  if (chosen.length !== 4 || !chosen.some(move => types.includes(move.type))) {
    throw new Error('Four supported moves with STAB unavailable for #' + pokemon.id);
  }
  return chosen;
}

async function build(id) {
  const [species, pokemon] = await Promise.all([
    fetchJson('https://pokeapi.co/api/v2/pokemon-species/' + id + '/'),
    fetchJson('https://pokeapi.co/api/v2/pokemon/' + id + '/')
  ]);
  const expected = LEGENDARY_IDS.includes(id) ? 'is_legendary' : 'is_mythical';
  if (species[expected] !== true || pokemon.id !== id) {
    throw new Error('Unexpected species category for #' + id);
  }
  const types = pokemon.types.sort((a, b) => a.slot - b.slot).map(item => item.type.name);
  const stats = Object.fromEntries(pokemon.stats.map(item => [
    item.stat.name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()),
    item.base_stat
  ]));
  const generation = Number(species.generation.url.match(/\/(\d+)\/$/)?.[1]);
  if (!Number.isInteger(generation) || generation < 1 || generation > 9) {
    throw new Error('Invalid generation for #' + id);
  }
  return {
    id, name: pokemon.name, types,
    bst: Object.values(stats).reduce((sum, value) => sum + value, 0),
    generation,
    sprite: 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/' + id + '.png',
    legendary: species.is_legendary, mythical: species.is_mythical,
    stats, moves: chooseMoves(pokemon, types)
  };
}

async function main() {
  const entries = [];
  for (let index = 0; index < ids.length; index += 5) {
    entries.push(...await Promise.all(ids.slice(index, index + 5).map(build)));
  }
  const source = [
    '/* Generated by scripts/build-campaign-wild-special-catalog.js. No runtime API calls. */',
    '(function () {',
    '  const entries = Object.freeze(' + JSON.stringify(entries, null, 2) + '.map(entry =>',
    '    Object.freeze({ ...entry, types: Object.freeze(entry.types),',
    '      stats: Object.freeze(entry.stats), moves: Object.freeze(entry.moves.map(Object.freeze)) })));',
    '  const byId = Object.freeze(Object.fromEntries(entries.map(entry => [entry.id, entry])));',
    '  const api = Object.freeze({ entries, byId });',
    "  if (typeof module !== 'undefined' && module.exports) module.exports = api;",
    '  else { window.PBACampaign = window.PBACampaign || {};',
    '    window.PBACampaign.CampaignWildSpecialCatalog = api; }',
    '})();',
    ''
  ].join('\n');
  fs.writeFileSync(outputPath, source);
  process.stdout.write('Built ' + entries.length + ' special encounter species.\n');
}

main().catch(error => { process.stderr.write(String(error.stack || error) + '\n'); process.exitCode = 1; });
